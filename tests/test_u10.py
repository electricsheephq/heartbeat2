@pytest.mark.parametrize('kind', ['file', 'url'])
def test_R10_A4_regex_tick_deadline_and_gateway_thread(engine, tmp_path, kind):
    proc = subprocess.Popen([sys.executable, '-B', '-c', REGEX_DRIVER, str(ROOT), str(tmp_path/kind), kind],
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, start_new_session=True)
    try:
        stdout, stderr = proc.communicate(timeout=8)
    except subprocess.TimeoutExpired:
        os.killpg(proc.pid, signal.SIGKILL); proc.communicate()
        pytest.fail('regex tick exceeded 8 s; gateway GIL was blocked on the base candidate')
    assert proc.returncode == 0, stderr
    result = json.loads(stdout)
    assert result['elapsed'] < 8 and result['gap'] < 1, result
    assert result['state_unchanged'] and result['calls'] == 0 and result['error_streak'] == 1, result


